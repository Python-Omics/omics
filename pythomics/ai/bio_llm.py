class BioLLM:
    """
    Class in charge of handling communication with LLMs.
    Base use case: interpretation and preliminary analysis
    of a multi-omic signature

    OpenRouter is used by default, providing access to free
    models.
    """
    def __init__(self, api_key: str = None, provider: str = "openrouter", model: str = "meta-llama/llama-3-8b-instruct:free"):
        """
        Initializes the LLM client

        Params:
        api_key: str
            API key to access the LLM provider. 
            If None, the environment variable 'OPENROUTER_API_KEY' is looked up
        provider: str
            LLM provider to use: 'openrouter', 'openai', 'groq'.
        model: str
            Name of the model to use. By default, the free model
            'meta-llama/llama-3-8b-instruct:free' is used
        """
        self.model = model
        self.provider = provider
        
        if provider == "openrouter":
            self.api_key = api_key or os.environ.get("OPENROUTER_API_KEY")
            base_url = "https://openrouter.ai/api/v1"
        elif provider == "openai":
            self.api_key = api_key or os.environ.get("OPENAI_API_KEY")
            base_url = "https://api.openai.com/v1"
        elif provider == "groq":
            self.api_key = api_key or os.environ.get("GROQ_API_KEY")
            base_url = "https://api.groq.com/openai/v1"
        else:
            raise ValueError(f"Provider '{provider}' not supported.")

        self.client = OpenAI(
            base_url=base_url,
            api_key=self.api_key
        ) 

        
        # TODO: review this if necessary. generated by gemini
        self.system_prompt = (
            "You are an expert bioinformatician and senior computational oncologist. "
            "Your task is to analyze multi-omic signatures (biomarkers) extracted from integrative statistical models (e.g. sPLS-DA/DIABLO). "
            "You will be provided with a list of biomarkers (genes, proteins, miRNAs, etc.) organized by omic block, "
            "along with their 'Loading' (weight and importance in the model) and their known biological function.\n\n"
            "STRICT RULES:\n"
            "1. WRITING: Be concise, professional and clinical. Do not use greetings ('Hello', 'Here is your report'). Go straight to the analysis.\n"
            "2. STRUCTURE: Organize your response into:\n"
            "   - Global Summary (1 paragraph with the 'overall picture' of the altered processes).\n"
            "   - Findings by Omic Block (Which pathways stand out in mRNA, Proteins, etc., based on the high loadings).\n"
            "   - Biological Conclusion (Potential joint functional implications or suggestions to investigate).\n"
            "3. RIGOR: Base your analysis EXCLUSIVELY on the information and functions provided in the context. Do not invent functions for genes that say 'No information'. If the majority say 'No information', mention it as a limitation.\n"
            "4. LOADING MEANING: Variables with positive vs negative Loadings indicate expression in contrasting groups or opposite directions in the latent component. Analyze the contrasts if possible."
        )

    def generate_analysis(self, context_string: str):
        """
        Sends the structured context to the LLM to generate a preliminary
        analysis
        """
        if not context_string or str(context_string).strip() == "":
            return "No biomarker context was provided to analyze."
        
        logger.info(f"Sending data to the LLM ({self.model}) on {self.provider}...")
        
        try: 
            response = self.client.chat.completions.create(
                model=self.model,
                messages=[
                    {"role": "system", "content": self.system_prompt},
                    {"role": "user", "content": context_string}
                ],
                temperature=0.25, # TODO: ADJUST THIS VALUE, BUT ALWAYS KEEP IT LOW
                max_tokens=3000
            )

            analysis_text = response.choices[0].message.content
            
            finish_reason = response.choices[0].finish_reason
            if finish_reason == 'length':
                logger.warning("Warning: The model reached the token limit or server timeout.")
                analysis_text += "\n\n---\n**[SYSTEM WARNING]: The analysis was interrupted at this point due to the length (tokens) or timeout limits of the AI provider.**"

            logger.info("LLM analysis completed.")
            return analysis_text

        except Exception as e:
            error_msg = f"Error generating analysis with LLM: {str(e)}"
            logger.error(error_msg)
            return error_msg
